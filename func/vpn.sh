# Define default paths
VPN_DATA="$HESTIA/data/vpn"
VPN_SERVER_CONF="$VPN_DATA/server.conf"
VPN_PEERS_CONF="$VPN_DATA/peers.conf"
VPN_CLIENTS_DIR="$VPN_DATA/clients"
WG_IFACE="wg0"
WG_CONF="/etc/wireguard/${WG_IFACE}.conf"

# Format validator for VPN client name
is_vpn_client_format_valid() {
	if ! [[ "$1" =~ ^[a-zA-Z0-9][-a-zA-Z0-9_]{0,31}$ ]]; then
		check_result "$E_INVALID" "invalid VPN client name format :: $1"
	fi
}

# Format validator for routed CIDRs (e.g. 192.168.1.0/24 or comma-separated)
is_vpn_routed_nets_valid() {
	if [ -z "$1" ]; then
		return 0
	fi
	local nets
	IFS=',' read -r -a nets <<< "$1"
	for net in "${nets[@]}"; do
		net=$(echo "$net" | xargs)
		if ! [[ "$net" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}/([0-9]|[1-2][0-9]|3[0-2])$ ]]; then
			check_result "$E_INVALID" "invalid routed network CIDR :: $net"
		fi
	done
}

# Get next available IP address in the VPN subnet
# Default subnet: 10.66.66.0/24 (server takes .1)
get_next_vpn_ip() {
	local subnet_base
	local next_octet=2

	if [ -f "$VPN_SERVER_CONF" ]; then
		# shellcheck source=/dev/null
		source_conf "$VPN_SERVER_CONF"
	fi

	subnet_base=$(echo "${SUBNET:-10.66.66.0/24}" | cut -d'.' -f1-3)

	if [ -f "$VPN_PEERS_CONF" ]; then
		local used_octets
		used_octets=$(grep -o "IP='[0-9.]*'" "$VPN_PEERS_CONF" 2>/dev/null | sed -e "s/IP='//" -e "s/'//" | awk -F'.' '{print $4}' | sort -n)
		for oct in $used_octets; do
			if [ "$oct" -eq "$next_octet" ]; then
				next_octet=$((next_octet + 1))
			elif [ "$oct" -gt "$next_octet" ]; then
				break
			fi
		done
	fi

	if [ "$next_octet" -gt 254 ]; then
		check_result "$E_LIMIT" "VPN subnet range exhausted"
	fi

	echo "${subnet_base}.${next_octet}"
}

# Rebuild /etc/wireguard/wg0.conf from Hestia configuration files
sync_wireguard_config() {
	if [ ! -f "$VPN_SERVER_CONF" ]; then
		return 0
	fi

	# shellcheck source=/dev/null
	source_conf "$VPN_SERVER_CONF"

	local tmp_conf
	tmp_conf=$(mktemp)

	cat <<EOF > "$tmp_conf"
# WireGuard configuration generated by Hestia Control Panel
# DO NOT EDIT DIRECTLY - Managed via v-* commands and web UI

[Interface]
Address = ${SERVER_IP}/24
ListenPort = ${PORT}
PrivateKey = $(cat /etc/wireguard/server.key 2>/dev/null)

EOF

	if [ -f "$VPN_PEERS_CONF" ]; then
		while IFS= read -r line; do
			[ -z "$line" ] && continue
			parse_object_kv_list "$line"
			if [ "$SUSPENDED" = "no" ]; then
				local peer_allowed_ips="${IP}/32"
				if [ -n "$ROUTED_NETS" ]; then
					peer_allowed_ips="${peer_allowed_ips},${ROUTED_NETS}"
				fi

				cat <<EOF >> "$tmp_conf"
[Peer]
# Name: ${CLIENT}
# Comment: ${COMMENT}
PublicKey = ${PUBLIC_KEY}
PresharedKey = $(cat "/etc/wireguard/psk_${CLIENT}.key" 2>/dev/null)
AllowedIPs = ${peer_allowed_ips}

EOF
			fi
		done < "$VPN_PEERS_CONF"
	fi

	mkdir -p /etc/wireguard
	chmod 700 /etc/wireguard
	cp -f "$tmp_conf" "$WG_CONF"
	chmod 600 "$WG_CONF"
	rm -f "$tmp_conf"

	# Apply in-flight if interface is active without dropping connections
	if ip link show "$WG_IFACE" > /dev/null 2>&1; then
		if which wg-quick > /dev/null 2>&1 && which wg > /dev/null 2>&1; then
			wg syncconf "$WG_IFACE" <(wg-quick strip "$WG_IFACE" 2>/dev/null) > /dev/null 2>&1 || true
		fi
	fi
}

